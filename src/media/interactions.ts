import {
	ActionRowBuilder, ButtonInteraction, Client, Message, MessageContextMenuCommandInteraction,
	ModalBuilder, ModalSubmitInteraction, PermissionsBitField, TextInputBuilder, TextInputStyle,
} from 'discord.js';
import { prismaClient } from '../entry';
import { getServerSettings } from '../queries/get-server-settings';
import { mediaHelperSettings, mediaEnabledInChannel } from './settings';
import { findMediaLinks, mediaLinkFromUrl } from './sites';
import { ConvertOptions, MediaFormat, normalizeOptions, runConversion } from './engine';

const PREFIX = 'whtba:media:';
export const mediaMessageCommands = [
	{ name: 'Convert media', type: 3 },
	{ name: 'Upload to soundboard', type: 3 },
];
export const isMediaComponent = (id: string): boolean => id.startsWith(PREFIX);
export const isMediaContextCommand = (name: string): boolean => mediaMessageCommands.some(c => c.name === name);

const modalField = (id: string, label: string, required: boolean, placeholder: string, style = TextInputStyle.Short) =>
	new ActionRowBuilder<TextInputBuilder>().addComponents(
		new TextInputBuilder().setCustomId(id).setLabel(label).setRequired(required)
			.setPlaceholder(placeholder).setStyle(style).setMaxLength(style === TextInputStyle.Paragraph ? 140 : 90),
	);

const showConvertModal = (interaction: ButtonInteraction | MessageContextMenuCommandInteraction, messageId: string, format = '') => {
	const modal = new ModalBuilder().setTitle('WHTBA medya dönüştürme').setCustomId(PREFIX + 'convert:' + messageId)
		.addComponents(
			modalField('format','Format veya işlem',true,'mp3, wav, gif, mp4, webm, mute, reverse, speed, trim, caption'),
			modalField('start','Başlangıç (saniye) — isteğe bağlı',false,'0'),
			modalField('duration','Süre (saniye) — isteğe bağlı',false,'10'),
			modalField('speed','Hız (0.5–2) — isteğe bağlı',false,'1.25'),
			modalField('caption','Altyazı / meme metni — isteğe bağlı',false,'Buraya yaz',TextInputStyle.Paragraph),
		);
	// Modal text inputs do not support server-side default values on older discord.js.
	return interaction.showModal(modal);
};

const showSoundboardModal = (interaction: MessageContextMenuCommandInteraction, messageId: string) =>
	interaction.showModal(new ModalBuilder().setCustomId(PREFIX + 'soundboard:' + messageId)
		.setTitle('Soundboard yükleme').addComponents(modalField('sound-name','Ses adı (2–32 karakter)',true,'Meme sound')));

const findSourceUrl = (message: Message): string | null => {
	const link = findMediaLinks(message.content)[0];
	if (link) return link.original;
	const file = message.attachments.find(a => /^(video|audio)\//i.test(a.contentType || '') ||
		/\.(mp4|webm|mov|mkv|mp3|wav|m4a|ogg|gif)$/i.test(a.name || ''));
	if (file) return file.url;
	// Context menus on a reply generated by the bot can still resolve its source link.
	const originalUrl = /\[View original\]\(<(https?:\/\/[^>]+)>\)/.exec(message.content)?.[1];
	return originalUrl && mediaLinkFromUrl(originalUrl) ? originalUrl : null;
};

const getOriginalMessage = async (interaction: ButtonInteraction | ModalSubmitInteraction, id: string): Promise<Message> => {
	if (!/^\d{17,20}$/.test(id) || !interaction.channel?.isTextBased() || !('messages' in interaction.channel))
		throw new Error('Geçersiz kaynak mesaj.');
	const message = await interaction.channel.messages.fetch(id);
	if (!message) throw new Error('Orijinal mesaj bulunamadı.');
	return message;
};

const enabled = async (guildId: string, channelId: string) => {
	const record = await getServerSettings(guildId, prismaClient);
	const preferences = mediaHelperSettings(record?.settings);
	if (!mediaEnabledInChannel(preferences, channelId))
		throw new Error('Media-Helper bu kanalda kapalı.');
	return preferences;
};

const executeConversion = async (
	interaction: ButtonInteraction | ModalSubmitInteraction,
	source: Message,
	options: ConvertOptions,
) => {
	if (!interaction.guildId) throw new Error('Bu işlem sunucuda kullanılabilir.');
	const preferences = await enabled(interaction.guildId, interaction.channelId);
	await interaction.deferReply({ ephemeral: preferences.ephemeralReplies });
	const url = findSourceUrl(source);
	if (!url) throw new Error('Mesajda desteklenen bir video/ses dosyası veya bağlantısı bulunamadı.');
	const media = await runConversion(url, options);
	await interaction.editReply({
		content: '-# Kaynak: [View original](<' + url + '>)',
		files: [{ attachment: media.buffer, name: media.filename }],
	});
};

const executeSoundboard = async (interaction: ModalSubmitInteraction, source: Message, client: Client) => {
	if (!interaction.guildId || !interaction.guild) throw new Error('Bu işlem sunucuda kullanılabilir.');
	const preferences = await enabled(interaction.guildId, interaction.channelId);
	if (!preferences.soundboard) throw new Error('Soundboard yükleme bu sunucuda kapalı.');
	if (!interaction.memberPermissions?.has(1n << 43n))
		throw new Error('Soundboard için Ses/İfade Oluştur yetkisi gerekli.');
	const name = interaction.fields.getTextInputValue('sound-name').trim();
	if (name.length < 2 || name.length > 32) throw new Error('Sound adı 2-32 karakter olmalı.');
	await interaction.deferReply({ ephemeral: true });
	const url = findSourceUrl(source);
	if (!url) throw new Error('Yüklenebilir medya bulunamadı.');
	const media = await runConversion(url, normalizeOptions('soundboard'));
	const sound = 'data:audio/mpeg;base64,' + media.buffer.toString('base64');
	await client.rest.post('/guilds/' + interaction.guildId + '/soundboard-sounds', {
		body: { name, sound, volume: 1 },
	});
	await interaction.editReply({ content: 'Soundboard sesine eklendi: **' + name + '**' });
};

const reportError = async (interaction: ButtonInteraction | ModalSubmitInteraction, error: unknown) => {
	const content = 'Medya işlemi başarısız: ' + (error instanceof Error ? error.message : 'Bilinmeyen hata');
	try {
		if (interaction.deferred || interaction.replied) await interaction.editReply({ content: content.slice(0,1900) });
		else await interaction.reply({ content: content.slice(0,1900), ephemeral: true });
	} catch (nested) { console.error('Media interaction error:', nested, error); }
};

export const processMediaContext = async (interaction: MessageContextMenuCommandInteraction): Promise<void> => {
	if (!interaction.guildId) {
		await interaction.reply({ content: 'Bu komut sunucuda kullanılabilir.', ephemeral: true }); return;
	}
	try {
		const settings = await enabled(interaction.guildId, interaction.channelId);
		if (interaction.commandName === 'Convert media') {
			await showConvertModal(interaction, interaction.targetId);
		} else if (interaction.commandName === 'Upload to soundboard') {
			if (!settings.soundboard) throw new Error('Soundboard işlemi kapalı.');
			if (!interaction.memberPermissions?.has(1n << 43n)) throw new Error('Ses/İfade Oluştur izni gerekli.');
			await showSoundboardModal(interaction, interaction.targetId);
		}
	} catch (error) {
		await interaction.reply({ content: error instanceof Error ? error.message : 'Hata oluştu.', ephemeral: true });
	}
};

export const processMediaComponent = async (interaction: ButtonInteraction | ModalSubmitInteraction, client: Client) => {
	if (!interaction.guildId || !isMediaComponent(interaction.customId)) return;
	const parts = interaction.customId.slice(PREFIX.length).split(':');
	const action = parts[0];
	const id = parts[1];
	try {
		if (!/^\d{17,20}$/.test(id || '')) throw new Error('Geçersiz mesaj.');
		const source = await getOriginalMessage(interaction, id);
		if (interaction.isButton()) {
			const settings = await enabled(interaction.guildId, interaction.channelId);
			if (!settings.quickActions) throw new Error('Hızlı işlem butonları kapalı.');
			if (action === 'trim' || action === 'caption') {
				await showConvertModal(interaction, id, action);
				return;
			}
			if (!['mp3','gif','mute'].includes(action)) throw new Error('Bilinmeyen işlem.');
			await executeConversion(interaction, source, normalizeOptions(action));
		} else if (interaction.isModalSubmit()) {
			if (action === 'convert') {
				const value = (key: string) => interaction.fields.getTextInputValue(key) || '';
				const opts = normalizeOptions(value('format'), value('start'), value('duration'),
					value('speed'), value('caption'));
				await executeConversion(interaction, source, opts);
			} else if (action === 'soundboard') {
				await executeSoundboard(interaction, source, client);
			} else throw new Error('Bilinmeyen işlem.');
		}
	} catch (error) {
		await reportError(interaction, error);
	}
};
